type Config struct {
	Scopes               *scopeList          `yaml:"scopes"`
	Sources              []string            `yaml:"sources"`
	Roots                []string            `yaml:"roots"`
	LoadPoints           map[string]RawValue `yaml:"load_points"`
	PersonPolicy         string              `yaml:"person_policy"`
	PersonSource         string              `yaml:"person_source"`
	PersonalityLibraries []string            `yaml:"personality_libraries"`
	RosterSources        []string            `yaml:"roster_sources"`
	SkillLoadPoints      map[string]RawValue `yaml:"skill_load_points"`
	SkillCatalogManifest string              `yaml:"skill_catalog_manifest"`
	OperatingContext     []string            `yaml:"operating_context"`
	Appendix             []AppendixEntry     `yaml:"appendix"`

	// Kept so a relative appendix path resolves against the config file.
	SourcePath string `yaml:"-"`
}

// AppendixEntry is one configured tail block: exactly one of Text or Path,
// and an empty Roles list makes it global.
type AppendixEntry struct {
	Text  string   `yaml:"text"`
	Path  string   `yaml:"path"`
	Roles []string `yaml:"roles"`
}

// scopeList accepts a scalar or a sequence, mirroring v1's normalizer; its
// presence (not emptiness) is what turns scope filtering on.
type scopeList []string

func (s *scopeList) UnmarshalYAML(node *yaml.Node) error {
	if node.Kind == yaml.ScalarNode {
		*s = scopeList{node.Value}
		return nil
	}
	var values []string
	if err := node.Decode(&values); err != nil {
		return err
	}
	*s = values
	return nil
}

// RawValue keeps a load-point value's truthiness: null and false opt a
// harness out, a non-empty string sets its path.
type RawValue struct {
	node yaml.Node
}

func (r *RawValue) UnmarshalYAML(node *yaml.Node) error {
	r.node = *node
	return nil
}

func (r RawValue) truthy() bool {
	switch r.node.Tag {
	case "!!null":
		return false
	case "!!bool":
		return r.node.Value == "true"
	default:
		return r.node.Value != ""
	}
}

func LoadConfig(path string) (*Config, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var cfg Config
	if err := decodeStrictYAML(raw, path, &cfg); err != nil {
		return nil, err
	}
	if err := personpolicy.Validate(cfg.PersonPolicy, cfg.PersonSource); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	seenRepositories := map[string]bool{}
	for _, repository := range cfg.OperatingContext {
		if err := validateConfiguredRepository(repository); err != nil {
			return nil, fmt.Errorf("%s: operating_context: %w", path, err)
		}
		if seenRepositories[repository] {
			return nil, fmt.Errorf("%s: operating_context repeats %q", path, repository)
		}
		seenRepositories[repository] = true
	}
	if err := validateAppendix(cfg.Appendix); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	cfg.SourcePath = path
	return &cfg, nil
}

// Shape is all cascade can check, because it never loads a person; see the
// appendix section of docs/cascade.md for how a dead slug surfaces.
var roleSlugRe = regexp.MustCompile(`^[a-z][a-z0-9-]*$`)

func validateAppendix(entries []AppendixEntry) error {
	for index, entry := range entries {
		position := index + 1
		hasText := strings.TrimSpace(entry.Text) != ""
		hasPath := strings.TrimSpace(entry.Path) != ""
		if hasText == hasPath {
			return fmt.Errorf("appendix entry %d needs exactly one of text or path", position)
		}
		seen := map[string]bool{}
		for _, role := range entry.Roles {
			if !roleSlugRe.MatchString(role) {
				return fmt.Errorf("appendix entry %d role %q must be a lowercase slug", position, role)
			}
			if seen[role] {
				return fmt.Errorf("appendix entry %d repeats role %q", position, role)
			}
			seen[role] = true
		}
	}
	return nil
}

// AppendixBlock is a resolved entry: provenance fence, body, binding roles.
type AppendixBlock struct {
	Fence string
	Body  string
	Roles []string
}

// GatherAppendix resolves entries in listed order, returning the error
// strings GatherSources uses so a missing file warns rather than aborts.
func GatherAppendix(cfg *Config) ([]AppendixBlock, []string) {
	var blocks []AppendixBlock
	var errors []string
	for index, entry := range cfg.Appendix {
		position := index + 1
		roles := append([]string(nil), entry.Roles...)
		if text := strings.Trim(entry.Text, "\n"); strings.TrimSpace(text) != "" {
			blocks = append(blocks, AppendixBlock{
				Fence: appendixFence(fmt.Sprintf("agent-compose.yaml entry %d", position), roles),
				Body:  text,
				Roles: roles,
			})
			continue
		}
		resolved := ResolveConfiguredPath(expand(entry.Path), cfg.SourcePath, homeDir())
		info, err := os.Stat(resolved)
		if err != nil || info.IsDir() {
			errors = append(errors, fmt.Sprintf("appendix path not found: %s", resolved))
			continue
		}
		_, body, err := parseSource(resolved)
		if err != nil {
			errors = append(errors, fmt.Sprintf("read appendix %s: %v", resolved, err))
			continue
		}
		body = absolutizeLinks(stripNavigationSections(strings.Trim(body, "\n")), filepath.Dir(resolved))
		blocks = append(blocks, AppendixBlock{
			Fence: appendixFence(resolved, roles),
			Body:  body,
			Roles: roles,
		})
	}
	return blocks, errors
}

func appendixFence(origin string, roles []string) string {
	if len(roles) == 0 {
		return fmt.Sprintf("<!-- appendix: %s -->", origin)
	}
	return fmt.Sprintf("<!-- appendix: %s (roles: %s) -->", origin, strings.Join(roles, ", "))
}

func homeDir() string {
	home, err := os.UserHomeDir()
	if err != nil {
		return ""
	}
	return home
}

// path.Clean, not filepath.Clean: these are logical owner/repository
// identifiers, and filepath.Clean rejects every one of them on Windows.
func validateConfiguredRepository(value string) error {
	if value == "" || strings.Contains(value, `\`) || strings.HasPrefix(value, "/") || path.Clean(value) != value {
		return fmt.Errorf("repository %q must be a clean owner/repository path", value)
	}
	parts := strings.Split(value, "/")
	if len(parts) != 2 || parts[0] == "" || parts[1] == "" {
		return fmt.Errorf("repository %q must have owner/repository form", value)
	}
	return nil
}

func decodeStrictYAML(raw []byte, path string, value any) error {
	decoder := yaml.NewDecoder(bytes.NewReader(raw))
	decoder.KnownFields(true)
	if err := decoder.Decode(value); err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	var trailing any
	if err := decoder.Decode(&trailing); err != io.EOF {
		return fmt.Errorf("%s: trailing YAML document", path)
	}
	return nil
}

func expand(path string) string {
	if path == "~" || strings.HasPrefix(path, "~/") {
		home, err := os.UserHomeDir()
		if err == nil {
			return filepath.Join(home, strings.TrimPrefix(strings.TrimPrefix(path, "~"), "/"))
		}
	}
	return path
}

// ResolveConfiguredPath expands one host-config path against its config file
// and injectable home directory.
func ResolveConfiguredPath(value, configPath, home string) string {
	value = strings.TrimSpace(value)
	if value == "~" || strings.HasPrefix(value, "~/") {
		return filepath.Join(home, strings.TrimPrefix(strings.TrimPrefix(value, "~"), "/"))
	}
	if filepath.IsAbs(value) {
		return value
	}
	return filepath.Join(filepath.Dir(configPath), value)
}

// DefaultLoadPoints wires claude and codex; opencode stays opt-in via config.
func DefaultLoadPoints() map[string]string {
	home, err := os.UserHomeDir()
	if err != nil {
		return map[string]string{}
	}
	return map[string]string{
		"claude": filepath.Join(home, ".claude", "CLAUDE.md"),
		"codex":  filepath.Join(home, ".codex", "AGENTS.md"),
	}
}

// ResolveLoadPoints merges config overrides over the defaults; falsy values
// (null, false, empty) opt a harness out entirely.
func ResolveLoadPoints(cfg *Config) map[string]string {
	return resolvePoints(DefaultLoadPoints(), cfg.LoadPoints)
}

// OperatingBase renders the base for one harness and role: the load point's
// own sources, plus each appendix block bound to that role.
func OperatingBase(cfg *Config, harness, role string) (string, error) {
	body, tail, err := OperatingBaseParts(cfg, harness, role)
	if err != nil {
		return "", err
	}
	if tail == "" {
		return body, nil
	}
	return body + "\n" + tail, nil
}

// OperatingBaseParts splits that render into sources and appendix, for a caller
// that rewrites the sources before rendering them. See ComposeParts.
func OperatingBaseParts(cfg *Config, harness, role string) (string, string, error) {
	gathered, _ := GatherSources(cfg)
	filtering := cfg.Scopes != nil
	var machineScopes []string
	if filtering {
		machineScopes = *cfg.Scopes
	}
	selected := selectByHarness(SelectByScope(gathered, machineScopes, filtering), harness)
	if len(selected) == 0 {
		return "", "", fmt.Errorf("no operating-base sources matched harness %q", harness)
	}
	overrides := map[string]string{}
	for _, src := range selected {
		if override := discoverOverride(src, harness); override != "" {
			overrides[src] = override
		}
	}
	appendix, errs := GatherAppendix(cfg)
	if len(errs) > 0 {
		return "", "", fmt.Errorf("operating base: %s", strings.Join(errs, "; "))
	}
	return ComposeParts(selected, overrides, appendix, role)
}

